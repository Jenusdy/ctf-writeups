def rol8(x, n):
    n &= 7
    if n == 0:
        return x
    return ((x << n) | (x >> (8 - n))) & 0xff


def ror8(x, n):
    n &= 7
    if n == 0:
        return x
    return ((x >> n) | (x << (8 - n))) & 0xff


